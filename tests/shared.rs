    f.body.profile = Profile::Full(cshm::Profile {
        community: p.community,
        schema_version: 1,
        public: p.public,
        private: Default::default(),
    });
    assert!(
        matches!(f.issue().check(), Admission::Refused{reasons} if matches!(&reasons[0], Refusal::Profile(_)))
    );
    let Profile::Full(p) = &mut f.body.profile else {
        unreachable!()
    };
    p.private.insert("secret".into(), json!(true));
    let salt = cpns::Salt::from_bytes(vec![44; 16]).unwrap();
    f.credential.pins.push(Pin {
        field: "secret".into(),
        fingerprint: fingerprint("garden", "alice", "secret", &json!(true), &salt),
    });
    f.body.openings.push(Opening {
        field: "secret".into(),
        salt: salt.as_bytes().to_vec(),
    });
    assert!(matches!(
        f.issue().check(),
        Admission::Admitted {
            scope: Scope::Full,
            ..
        }
    ));
    let bound = f.credential.pins[1].fingerprint;
    f.credential.pins[1].fingerprint =
        *cpns::fingerprint(&pin_value_bytes(&json!(true)), &salt).as_bytes();
    refused(f.issue().check(), Refusal::Pin);
    f.credential.pins[1].fingerprint = bound;
    f.body.profile = Profile::Public(profile("garden"));
    // Public projections must not carry private opening material.
    refused(f.issue().check(), Refusal::Pin);
    f.body.openings.pop();
    assert!(matches!(
        f.issue().check(),
        Admission::Admitted {
            scope: Scope::Public,
            ..
        }
    ));
