shared_test!(
    noncanonical_cose_is_refused_at_every_verification_boundary,
    {
        use cgrd::storage::{SnapshotKind, SnapshotRecord, StorageError};

        let mut f = Fixture::new();
        let signed = f.issue();
        assert!(signed.check().is_admitted());
        for (kind, canonical) in [
            (csgn::Kind::Credential, f.body.credential.clone()),
            (csgn::Kind::SettingsSnapshot, signed.settings.clone()),
            (csgn::Kind::SchemaSnapshot, signed.schema.clone()),
        ] {
            for alternate in alternate_cose_encodings(&canonical) {
                // A permissive COSE decoder still sees the same signed content.
                // Refusal must come from canonical framing, not a broken signature.
                let decoded = CoseSign1::from_tagged_slice(&alternate).unwrap();
                assert_eq!(decoded.clone().to_tagged_vec().unwrap(), canonical);
                let key = ed25519_dalek::VerifyingKey::from_bytes(
                    &signed.keys.active().unwrap().public_key(),
                )
                .unwrap();
                decoded
                    .verify_signature(&[], |signature, message| {
                        key.verify_strict(
                            message,
                            &ed25519_dalek::Signature::from_slice(signature).unwrap(),
                        )
                    })
                    .unwrap();
                assert!(matches!(
                    signed.keys.verify(&alternate, kind, NOW),
                    Err(csgn::VerifyError::Malformed(_))
                ));

                let mut s = f.issue();
                if kind == csgn::Kind::Credential {
                    let mut body = f.body.clone();
                    body.credential = alternate;
                    s.bundle.payload = serde_json::to_vec(&body).unwrap();
                    s.bundle.signature = f
                        .device
                        .sign(&binding_bytes(&s.bundle.payload))
                        .to_bytes()
                        .to_vec();
                    refused(s.check(), Refusal::Credential);
                } else {
                    let snapshot_kind = if kind == csgn::Kind::SettingsSnapshot {
                        s.settings = alternate.clone();
                        SnapshotKind::Settings
                    } else {
                        s.schema = alternate.clone();
                        SnapshotKind::Schema
                    };
                    refused(s.check(), Refusal::Snapshot);
                    assert!(matches!(
                        SnapshotRecord::verify("garden", &s.keys, snapshot_kind, &alternate, NOW),
                        Err(StorageError::Invalid)
                    ));
                }
            }
        }
    }
);

shared_test!(authenticated_ring_lifetime_policy_is_enforced, {
    use cgrd::storage::{SnapshotKind, SnapshotRecord, StorageError};

    let mut f = Fixture::new();
    let mut s = f.issue();
    let boundary = issuer_with_lifetime("garden", EXPIRY - ISSUED);
    s.keys = boundary.key_ring().clone();
    assert!(s.check().is_admitted());
    let limited = issuer_with_lifetime("garden", EXPIRY - ISSUED - 1);
    let short_settings = f
        .issuer
        .sign(
            csgn::Kind::SettingsSnapshot,
            &serde_json::to_vec(&f.settings).unwrap(),
            ISSUED,
            EXPIRY - 1,
        )
        .unwrap();
    let short_schema = f
        .issuer
        .sign(
            csgn::Kind::SchemaSnapshot,
            &serde_json::to_vec(&f.schema).unwrap(),
            ISSUED,
            EXPIRY - 1,
        )
        .unwrap();
    for kind in [
        csgn::Kind::Credential,
        csgn::Kind::SettingsSnapshot,
        csgn::Kind::SchemaSnapshot,
    ] {
        let mut s = f.issue();
        s.keys = limited.key_ring().clone();
        if kind != csgn::Kind::SettingsSnapshot {
            s.settings = short_settings.clone();
        }
        if kind != csgn::Kind::SchemaSnapshot {
            s.schema = short_schema.clone();
        }
        if kind == csgn::Kind::Credential {
            refused(s.check(), Refusal::Credential);
        } else {
            refused(s.check(), Refusal::Snapshot);
            let (snapshot_kind, bytes) = if kind == csgn::Kind::SettingsSnapshot {
                (SnapshotKind::Settings, &s.settings)
            } else {
                (SnapshotKind::Schema, &s.schema)
            };
            assert!(matches!(
                SnapshotRecord::verify("garden", &s.keys, snapshot_kind, bytes, NOW),
                Err(StorageError::Invalid)
            ));
        }
    }
});

