use serde::{Deserialize, Serialize};

/// Maximum serialized bundle or snapshot size, in bytes.
pub const MAX_DOCUMENT_BYTES: usize = 1 << 20;
/// Maximum number of fields, gates, device keys, openings or personal rules.
pub const MAX_ITEMS: usize = 256;

/// A successful community gate, containing no raw evidence.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Gate {
    /// Gate identifier.
    pub gate: String,
    /// Provider identifier.
    pub provider: String,
    /// Exclusive expiry, in caller-supplied Unix seconds.
    pub valid_until: u64,
}

/// A signed pin over one schema field. Field identifiers span both parts.
#[derive(Clone, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Pin {
    /// Schema field identifier.
    pub field: String,
    /// cpns v2 fingerprint bytes, bound to the credential community/member and field.
    pub fingerprint: [u8; 32],
}

/// Required owner-versioned community admission assertion.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub enum CredentialPurpose {
    /// Community admission under the complete configured issuer action.
    #[serde(rename = "cplc.community-credential.v2")]
    CommunityCredentialV2,
}

/// JSON payload inside a csgn `Credential` COSE_Sign1.
/// Issuer, issued time, expiry and key ID live in csgn's protected envelope.
#[derive(Clone, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Credential {
    /// Exact owner format; older unbound credentials are refused.
    pub purpose: CredentialPurpose,
    /// Complete issuer action that passed before this credential was signed.
    pub issuance_action: String,
    /// Issuing community; must also equal the trusted key ring's issuer.
    pub community: String,
    /// Community pseudonym.
    pub member: String,
    /// Canonical handle.
    pub handle: String,
    /// Exact schema version.
    pub schema_version: u32,
    /// Admission epoch.
    pub policy_epoch: u64,
    /// Passed community gates; subject is this member, level is community.
    pub gates: Vec<Gate>,
    /// Restricted field fingerprints.
    pub pins: Vec<Pin>,
    /// Authorized Ed25519 device public keys, certified by the community.
    pub devices: Vec<[u8; 32]>,
}

/// A required gate with an explicit provider allowlist.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct GateRequirement {
    /// Gate identifier.
    pub gate: String,
    /// Nonempty list of acceptable providers.
    pub providers: Vec<String>,
}

/// Resolved guard settings, supplied in a signed settings snapshot.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Settings {
    /// All listed gate requirements must be satisfied.
    pub required_gates: Vec<GateRequirement>,
    /// Current member revocations, applied before admission.
    pub revoked_members: Vec<String>,
    /// Current device revocations across this community.
    pub revoked_devices: Vec<[u8; 32]>,
    /// Reserved handles, compared after PRECIS and skeleton normalization.
    pub reserved_handles: Vec<String>,
}

/// JSON payload inside a csgn settings or schema snapshot.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Snapshot<T> {
    /// Community namespace, equal to the issuer.
    pub community: String,
    /// Positive, monotonically increasing revision of this snapshot kind.
    pub revision: u64,
    /// Admission epoch shared by credential, settings and schema snapshot.
    pub policy_epoch: u64,
    /// Settings or cshm schema.
    pub content: T,
}

/// Public-only and complete validation are distinct signed presentations.
#[derive(Clone, Deserialize, PartialEq, Serialize)]
#[serde(
    tag = "scope",
    content = "profile",
    rename_all = "snake_case",
    deny_unknown_fields
)]
pub enum Profile {
    /// Used by the forum; has no place for private values or openings.
    Public(cshm::PublicProfile),
    /// Used locally on a device or by an authorized recipient.
    Full(cshm::Profile),
}

impl Profile {
    pub(crate) fn answer(&self, field: &str) -> Option<&serde_json::Value> {
        match self {
            Self::Public(profile) => profile.public.get(field),
            Self::Full(profile) => profile
                .public
                .get(field)
                .or_else(|| profile.private.get(field)),
        }
    }
}

/// A device-owned salt. No copy of the field value is accepted here.
/// Deliberately has no Debug implementation; never persist an opening.
#[derive(Clone, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Opening {
    /// Field whose signed pin is being opened.
    pub field: String,
    /// At least 16 bytes, independently generated by the holder for each change.
    pub salt: Vec<u8>,
}

/// Serialized once, then signed as a whole by the authorized device.
#[derive(Clone, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct BundleContent {
    /// Community namespace.
    pub community: String,
    /// Member pseudonym, equal to the signed credential's subject.
    pub member: String,
    /// Device public key, present in the signed credential's authorization list.
    pub device: [u8; 32],
    /// Complete csgn credential COSE bytes.
    pub credential: Vec<u8>,
    /// Profile in the signed validation scope.
    pub profile: Profile,
    /// Openings for all presented pinned fields, and no other fields.
    pub openings: Vec<Opening>,
}

/// The exact JSON bytes and detached Ed25519 signature of a presentation.
/// Sign [`binding_bytes`] of `payload`; do not reserialize received bytes.
#[derive(Clone, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Bundle {
    /// UTF-8 JSON encoding of [`BundleContent`].
    pub payload: Vec<u8>,
    /// Exactly 64 signature bytes.
    pub signature: Vec<u8>,
}

/// Build the domain-separated message for a device's Ed25519 signing API.
/// This framing is not a cryptographic primitive; dalek performs verification.
pub fn binding_bytes(payload: &[u8]) -> Vec<u8> {
    let mut bytes = b"cgrd:bundle:v1\0".to_vec();
    bytes.extend_from_slice(payload);
    bytes
}

/// Pin encoding v1: compact JSON, recursively sorted object keys; number
/// spellings are retained. In particular, `34` and `34.0` are distinct pins.
/// Call this before `cpns::fingerprint_v2` with the credential's community/member
/// and schema field ID. The value encoding is v1; fingerprints must use cpns v2.
pub fn pin_value_bytes(value: &serde_json::Value) -> Vec<u8> {
    let mut value = value.clone();
    value.sort_all_objects();
    serde_json::to_vec(&value).expect("JSON values serialize without failure")
}
